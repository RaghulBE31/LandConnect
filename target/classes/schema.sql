CREATE TABLE IF NOT EXISTS plots (
  id VARCHAR(40) PRIMARY KEY,
  city VARCHAR(100) NOT NULL,
  district VARCHAR(100) NOT NULL,
  locality VARCHAR(120) NOT NULL,
  land_type VARCHAR(40) NOT NULL,
  price BIGINT NOT NULL,
  acres DOUBLE PRECISION NOT NULL,
  approved BOOLEAN NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  owner_email VARCHAR(255),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  payload TEXT NOT NULL
);
ALTER TABLE plots ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE plots ADD COLUMN IF NOT EXISTS created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL;

CREATE TABLE IF NOT EXISTS users (
  email VARCHAR(255) PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  phone VARCHAR(30),
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
ALTER TABLE plots ADD COLUMN IF NOT EXISTS owner_email VARCHAR(255);
ALTER TABLE plots ADD COLUMN IF NOT EXISTS review_status VARCHAR(20) NOT NULL DEFAULT 'APPROVED';

CREATE TABLE IF NOT EXISTS enquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plot_id VARCHAR(40) NOT NULL,
  buyer_email VARCHAR(255),
  name VARCHAR(120) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  email VARCHAR(255),
  request_type VARCHAR(20) NOT NULL,
  preferred_date VARCHAR(30),
  message VARCHAR(1000),
  status VARCHAR(20) NOT NULL DEFAULT 'NEW',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_enquiry_plot FOREIGN KEY (plot_id) REFERENCES plots(id)
);
ALTER TABLE enquiries ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'NEW';

CREATE TABLE IF NOT EXISTS plot_photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plot_id VARCHAR(40) NOT NULL,
  image_url VARCHAR(500) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_photo_plot FOREIGN KEY (plot_id) REFERENCES plots(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS saved_plots (
  user_email VARCHAR(255) NOT NULL,
  plot_id VARCHAR(40) NOT NULL,
  saved_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  PRIMARY KEY (user_email, plot_id),
  CONSTRAINT fk_saved_user FOREIGN KEY (user_email) REFERENCES users(email) ON DELETE CASCADE,
  CONSTRAINT fk_saved_plot FOREIGN KEY (plot_id) REFERENCES plots(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS notification_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquiry_id BIGINT NOT NULL,
  recipient VARCHAR(255) NOT NULL,
  recipient_kind VARCHAR(20) NOT NULL,
  status VARCHAR(40) NOT NULL,
  error_message VARCHAR(500),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_notification_enquiry FOREIGN KEY (enquiry_id) REFERENCES enquiries(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS support_queries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL,
  topic VARCHAR(80) NOT NULL,
  message VARCHAR(3000) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
  email_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
ALTER TABLE support_queries ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'OPEN';

CREATE TABLE IF NOT EXISTS app_migrations (
  migration_key VARCHAR(120) PRIMARY KEY,
  applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS prebookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plot_id VARCHAR(40) NOT NULL REFERENCES plots(id),
  buyer_email VARCHAR(255) NOT NULL REFERENCES users(email),
  buyer_name VARCHAR(120) NOT NULL,
  phone VARCHAR(30),
  message VARCHAR(1000),
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  expires_at TIMESTAMP,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT ck_prebooking_status CHECK (status IN ('PENDING','APPROVED','DECLINED','CANCELLED','EXPIRED'))
);
ALTER TABLE prebookings ADD COLUMN IF NOT EXISTS expires_at TIMESTAMP;
ALTER TABLE prebookings DROP CONSTRAINT IF EXISTS ck_prebooking_status;
ALTER TABLE prebookings ADD CONSTRAINT ck_prebooking_status CHECK (status IN ('PENDING','APPROVED','DECLINED','CANCELLED','EXPIRED'));
CREATE UNIQUE INDEX IF NOT EXISTS uq_prebooking_pending_buyer_plot
  ON prebookings(plot_id,buyer_email) WHERE status='PENDING';
CREATE UNIQUE INDEX IF NOT EXISTS uq_prebooking_reserved_plot
  ON prebookings(plot_id) WHERE status='APPROVED';
